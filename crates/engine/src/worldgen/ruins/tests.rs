use super::*;
use crate::block::{self, GRASS, LOG};
use crate::worldgen::WorldGen;

const SEEDS: [u32; 4] = [2024, 1337, 7, 99];

fn block_at(g: &mut WorldGen, p: IVec3) -> BlockId {
    let c = g.generate(IVec3::new(p.x >> 5, p.y >> 5, p.z >> 5));
    c.get((p.x & 31) as usize, (p.y & 31) as usize, (p.z & 31) as usize)
}

fn count(r: &Ruin, id: BlockId) -> usize {
    r.blocks.iter().filter(|(_, b)| *b == id).count()
}

/// A flat site at y = 70 with grass on top.
fn flat(seed: u32) -> Ruin {
    build(seed, 1000, -400, 70, GRASS, false, |_, _| 70)
}

fn with_vault(seed: u32) -> Ruin {
    build(seed, 1000, -400, 70, GRASS, true, |_, _| 70)
}

/// The block a ruin sets at `p` (the last entry wins, as when stamping).
fn set_at(r: &Ruin, p: IVec3) -> Option<BlockId> {
    r.blocks.iter().rev().find(|(q, _)| *q == p).map(|(_, id)| *id)
}

#[test]
fn the_first_ruin_is_150_to_300_blocks_from_the_spawn() {
    for seed in 0..200 {
        for attempt in 0..ATTEMPTS {
            let (x, z) = candidate(seed, 0, 0, attempt);
            let d = f64::from(x * x + z * z).sqrt();
            assert!((150.0..=300.0).contains(&d), "seed {seed} attempt {attempt}: {d:.0} blocks");
        }
    }
}

#[test]
fn other_candidates_keep_inside_their_region() {
    for seed in [5, 6] {
        for (rx, rz) in [(1, 0), (-1, 0), (0, 3), (-4, -2), (7, 7)] {
            for attempt in 0..ATTEMPTS {
                let (x, z) = candidate(seed, rx, rz, attempt);
                assert_eq!((region_of(x), region_of(z)), (rx, rz));
                assert!((x - (rx * REGION - REGION / 2)).min(rx * REGION + REGION / 2 - x) >= MARGIN);
                assert!((z - (rz * REGION - REGION / 2)).min(rz * REGION + REGION / 2 - z) >= MARGIN);
            }
        }
    }
}

#[test]
fn a_ruin_has_its_parts_and_stays_in_reach() {
    let r = flat(1);
    assert!(count(&r, RUSTED_MACHINE) >= 4, "three husks on the slab and one at the shaft's foot");
    assert!((2..=5).contains(&(count(&r, RUSTED_GIRDER) / 2)), "two poles, two to five high");
    assert!(count(&r, SPENT_ROCK) >= 20, "the shaft ends in spent rock");
    assert!(count(&r, CONCRETE) > 40, "a cracked slab");
    assert!(count(&r, GRASS) > 15, "cracks show the ground");
    for (p, _) in &r.blocks {
        assert!((p.x - r.x).abs() <= RADIUS && (p.z - r.z).abs() <= RADIUS, "{p:?} is out of reach");
    }
    assert!(r.top >= 71 && r.top <= 76, "{}", r.top);
    assert!(r.bottom <= 70 - 10 && r.bottom >= 70 - 15, "{}", r.bottom);
}

#[test]
fn building_is_deterministic_and_varies() {
    let (a, b) = (flat(1), flat(1));
    assert!(a.blocks == b.blocks);
    let layouts = (0..20).filter(|&s| flat(s).blocks != a.blocks).count();
    assert!(layouts >= 18, "ruins of different seeds repeat each other");
}

#[test]
fn a_slab_follows_the_ground_it_stands_on() {
    // A slope: the slab stays level, so the high side is cut and the low side filled.
    let r = build(3, 0, 0, 70, GRASS, false, |x, _| 70 + x.clamp(-3, 3));
    let at = |x: i32, y: i32, z: i32| r.blocks.iter().rev().find(|(p, _)| *p == IVec3::new(x, y, z)).map(|b| b.1);
    assert_eq!(at(3, 72, 5), Some(AIR), "the hill is cut down to the slab");
    assert_eq!(at(-3, 68, 5), Some(DIRT), "and the hollow filled up to it");
    assert!(matches!(at(-3, 70, 5), Some(CONCRETE | GRASS)));
}

#[test]
fn every_seed_has_a_first_ruin_on_flat_dry_land() {
    for seed in SEEDS {
        let g = WorldGen::new(seed);
        let r = g.ruin_at(0, 0).unwrap_or_else(|| panic!("seed {seed} has no first ruin"));
        let d = f64::from(r.x * r.x + r.z * r.z).sqrt();
        assert!((150.0..=300.0).contains(&d), "seed {seed}: {d:.0} blocks away");
        let heights: Vec<i32> =
            [-6, 0, 6].iter().flat_map(|&dz| [-6, 0, 6].map(|dx| g.height_at(r.x + dx, r.z + dz))).collect();
        let (lo, hi) = (*heights.iter().min().unwrap(), *heights.iter().max().unwrap());
        assert!(hi - lo <= MAX_RELIEF && lo > SEA_LEVEL, "seed {seed}: ground {lo}..{hi}");
    }
}

